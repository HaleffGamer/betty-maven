-- Tabelas do sistema. Roda a cada início, mas só cria o que ainda não existe.

CREATE TABLE IF NOT EXISTS barbeiros (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(60) NOT NULL,
    ativo BOOLEAN     NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS servicos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR(60)   NOT NULL,
    duracao_minutos  INT           NOT NULL,
    preco            DECIMAL(10,2) NOT NULL,
    ativo            BOOLEAN       NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS usuarios (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome         VARCHAR(60)  NOT NULL,
    login        VARCHAR(30)  NOT NULL UNIQUE,
    senha_hash   VARCHAR(200) NOT NULL,
    papel        VARCHAR(20)  NOT NULL,
    barbeiro_id  BIGINT REFERENCES barbeiros (id)
);

CREATE TABLE IF NOT EXISTS agendamentos (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barbeiro_id       BIGINT       NOT NULL REFERENCES barbeiros (id),
    servico_id        BIGINT       NOT NULL REFERENCES servicos (id),
    cliente_nome      VARCHAR(80)  NOT NULL,
    cliente_telefone  VARCHAR(30)  NOT NULL,
    dia               DATE         NOT NULL,
    hora_inicio       TIME         NOT NULL,
    -- o mesmo barbeiro não pode ter dois agendamentos começando no mesmo minuto
    CONSTRAINT uq_barbeiro_horario UNIQUE (barbeiro_id, dia, hora_inicio)
);

CREATE INDEX IF NOT EXISTS idx_agendamentos_barbeiro_dia ON agendamentos (barbeiro_id, dia);
